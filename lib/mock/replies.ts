const daysAgo = (d: number, h = 12, m = 0) => {
  const date = new Date();
  date.setDate(date.getDate() - d);
  date.setHours(h, m, 0, 0);
  return date.toISOString();
};

const minsAgo = (m: number) => {
  const date = new Date();
  date.setMinutes(date.getMinutes() - m);
  return date.toISOString();
};

